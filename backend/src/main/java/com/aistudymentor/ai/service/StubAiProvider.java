package com.aistudymentor.ai.service;

import com.aistudymentor.ai.dto.AnswerRequest;
import com.aistudymentor.ai.dto.ExplanationStep;
import com.aistudymentor.ai.dto.GeneratedQuiz;
import com.aistudymentor.ai.dto.GeneratedQuizQuestion;
import com.aistudymentor.ai.dto.QuizRequest;
import com.aistudymentor.ai.dto.StructuredAnswer;
import org.springframework.boot.autoconfigure.condition.ConditionalOnProperty;
import org.springframework.stereotype.Service;

import java.util.ArrayList;
import java.util.List;

@Service
@ConditionalOnProperty(name = "ai.provider", havingValue = "stub")
public class StubAiProvider implements AiProvider {

    @Override
    public StructuredAnswer answer(AnswerRequest request) {
        return StructuredAnswer.builder()
                .subject(request.getSubject())
                .difficulty("demo")
                .summary("Demo AI response. No real answer was generated by an AI provider.")
                .steps(List.of(ExplanationStep.builder()
                        .stepNumber(1)
                        .title("Demo response")
                        .explanation("Configure the Gemini provider to receive a real academic explanation.")
                        .build()))
                .finalAnswer("Demo only")
                .keyConcepts(List.of("This is a test or demo response."))
                .commonMistakes(List.of("Do not treat this demo as a verified answer."))
                .followUpQuestions(List.of("Configure Gemini to generate a real answer."))
                .modelId("stub")
                .promptVersion("answer/v1")
                .inputTokens(0)
                .outputTokens(0)
                .cacheHit(false)
                .build();
    }

    @Override
    public GeneratedQuiz generateQuiz(QuizRequest request) {
        List<GeneratedQuizQuestion> questions = new ArrayList<>();
        for (int i = 1; i <= request.getNumQuestions(); i++) {
            questions.add(GeneratedQuizQuestion.builder()
                    .type("MCQ")
                    .topic(request.getTopic() == null ? request.getSubject() : request.getTopic())
                    .prompt("Demo quiz question " + i + " (not for assessment)")
                    .options(List.of("Demo A", "Demo B", "Demo C"))
                    .correctAnswer("Demo A")
                    .acceptedAnswers(List.of())
                    .explanation("Demo content. Configure Gemini for generated questions.")
                    .build());
        }
        return GeneratedQuiz.builder()
                .questions(questions)
                .modelId("stub")
                .promptVersion("quiz/v1")
                .inputTokens(0)
                .outputTokens(0)
                .build();
    }

    @Override
    public String modelId() {
        return "stub";
    }
}
